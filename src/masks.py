"""
Модуль с функциями для маскировки банковских данных.
"""


def get_mask_card_number(card_number: str) -> str:
    """
    Маскирует номер банковской карты.

    Формат: XXXX XX** **** XXXX

    Параметры:
    - card_number: номер карты (16 цифр)

    Возвращает:
    - Замаскированный номер карты

    Пример:
    >>> get_mask_card_number("7000792289606361")
    "7000 79** **** 6361"
    """
    # Проверяем, что номер карты содержит только цифры и имеет достаточную длину
    if len(card_number) < 16:
        return "Недостаточно цифр для маскировки"

    return f"{card_number[:4]} {card_number[4:6]}** **** {card_number[-4:]}"


def get_mask_account(account_number: str) -> str:
    """
    Маскирует номер банковского счета.

    Формат: **XXXX

    Параметры:
    - account_number: номер счета

    Возвращает:
    - Замаскированный номер счета

    Пример:
    >>> get_mask_account("73654108430135874305")
    "**4305"
    """
    # Проверяем, что номер счета содержит достаточно цифр
    if len(account_number) < 4:
        return "Недостаточно цифр для маскировки"

    return f"**{account_number[-4:]}"


if __name__ == "__main__":
    # Примеры использования
    print(get_mask_card_number("7000792289606361"))
    print(get_mask_account("73654108430135874305"))
