"""
Модуль с функциями для маскировки банковских данных.
Содержит функции для маскировки номеров карт и счетов.
"""


def get_mask_card_number(card_number: str) -> str:
    """
    Маскирует номер банковской карты.

    Формат: XXXX XX** **** XXXX
    - Первые 4 цифры видны полностью
    - Следующие 2 цифры видны полностью
    - Последние 4 цифры видны полностью
    - Остальные заменяются на *

    Параметры:
    - card_number: номер карты (строка из 16 цифр)

    Возвращает:
    - Замаскированный номер карты в формате "XXXX XX** **** XXXX"

    Пример:
    >>> get_mask_card_number("7000792289606361")
    "7000 79** **** 6361"
    """
    # Проверяем, что номер карты содержит достаточно цифр
    if len(card_number) < 16:
        return "Недостаточно цифр для маскировки"

    # Извлекаем части номера
    first_four = card_number[:4]        # первые 4 цифры
    next_two = card_number[4:6]          # следующие 2 цифры (5-6 позиции)
    last_four = card_number[-4:]         # последние 4 цифры

    # Формируем замаскированный номер
    return f"{first_four} {next_two}** **** {last_four}"


def get_mask_account(account_number: str) -> str:
    """
    Маскирует номер банковского счета.

    Формат: **XXXX (видны только последние 4 цифры)

    Параметры:
    - account_number: номер счета (строка цифр)

    Возвращает:
    - Замаскированный номер счета в формате "**XXXX"

    Пример:
    >>> get_mask_account("73654108430135874305")
    "**4305"
    """
    # Проверяем, что номер счета содержит достаточно цифр
    if len(account_number) < 4:
        return "Недостаточно цифр для маскировки"

    # Берем последние 4 цифры и добавляем ** спереди
    return f"**{account_number[-4:]}"


